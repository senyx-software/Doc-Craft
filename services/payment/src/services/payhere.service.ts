/**
 * payhere.service.ts — PayHere integration (Sri Lanka / LKR).
 *
 * PayHere is used for Sri Lankan customers paying in LKR.
 * It does NOT have an official Node.js SDK, so we interact with it directly:
 *
 *   1. Generate a checkout hash for the payment form
 *   2. Verify incoming webhook notifications using MD5 hash verification
 *   3. Parse PayHere payment_status codes into DocCraft subscription actions
 *
 * PayHere docs: https://support.payhere.lk/api-&-mobile-sdk/payhere-checkout
 */

import crypto from 'crypto';
import { env } from '../config/env.js';
import { prisma } from '../db/prisma.js';
import {
  isAlreadyProcessed,
  markProcessed,
  activateProSubscription,
  downgradeToFree,
  upsertInvoice,
  queueNotification,
  emitAutomationEvent,
  trackProductEvent,
} from './subscription.service.js';

// PayHere payment_status codes
export const PAYHERE_STATUS = {
  SUCCESS:       2,
  PENDING:       0,
  CANCELLED:    -1,
  FAILED:       -2,
  CHARGEBACKED: -3,
} as const;

export type PayhereStatus = (typeof PAYHERE_STATUS)[keyof typeof PAYHERE_STATUS];

export interface PayhereCheckoutData {
  merchant_id:     string;
  return_url:      string;
  cancel_url:      string;
  notify_url:      string;
  order_id:        string;
  items:           string;
  currency:        string;
  amount:          string;   // "990.00"
  first_name:      string;
  last_name:       string;
  email:           string;
  phone:           string;
  address:         string;
  city:            string;
  country:         string;
  hash:            string;   // generated by generateHash()
  recurrence?:     string;   // "1 Month" for recurring
  duration?:       string;   // "Forever" for subscription
  custom_1?:       string;   // userId
  custom_2?:       string;   // planId
}

/**
 * generateHash — creates the PayHere checkout hash.
 *
 * Formula (from PayHere docs):
 *   MD5( merchant_id + order_id + amount + currency + MD5(merchant_secret).toUpperCase() ).toUpperCase()
 */
export function generateHash(
  orderId: string,
  amount: string,
  currency: string,
): string {
  const merchantSecretHash = crypto
    .createHash('md5')
    .update(env.PAYHERE_MERCHANT_SECRET)
    .digest('hex')
    .toUpperCase();

  const raw = `${env.PAYHERE_MERCHANT_ID}${orderId}${amount}${currency}${merchantSecretHash}`;
  return crypto.createHash('md5').update(raw).digest('hex').toUpperCase();
}

/**
 * verifyWebhookHash — verifies an incoming PayHere IPN notification.
 *
 * PayHere sends a `md5sig` parameter in the webhook body.
 * We recompute it and compare.
 *
 * Formula:
 *   MD5( merchant_id + order_id + amount + currency_code + status_code + MD5(secret).toUpperCase() ).toUpperCase()
 */
export function verifyWebhookHash(params: {
  merchant_id:    string;
  order_id:       string;
  payhere_amount: string;
  payhere_currency: string;
  status_code:    string;
  md5sig:         string;
}): boolean {
  if(!env.PAYHERE_MERCHANT_ID || !env.PAYHERE_MERCHANT_SECRET)return false;
  const { merchant_id, order_id, payhere_amount, payhere_currency, status_code, md5sig } = params;

  const merchantSecretHash = crypto
    .createHash('md5')
    .update(env.PAYHERE_MERCHANT_SECRET)
    .digest('hex')
    .toUpperCase();

  const raw = `${merchant_id}${order_id}${payhere_amount}${payhere_currency}${status_code}${merchantSecretHash}`;
  const computed = crypto.createHash('md5').update(raw).digest('hex').toUpperCase();

  if (merchant_id !== env.PAYHERE_MERCHANT_ID || typeof md5sig !== 'string' || !/^[a-fA-F0-9]{32}$/.test(md5sig)) return false;
  return crypto.timingSafeEqual(Buffer.from(computed), Buffer.from(md5sig.toUpperCase()));
}

/**
 * buildCheckoutData — builds the full PayHere form data for a Pro subscription.
 *
 * @param userId    DocCraft user ID (stored in custom_1)
 * @param planId    Plan DB id (stored in custom_2)
 * @param orderId   Unique order ID (UUID)
 * @param amount    e.g. "990.00"
 * @param email     User email
 */
export function buildCheckoutData(params: {
  userId:   string;
  planId:   string;
  orderId:  string;
  amount:   string;
  email:    string;
  firstName?: string;
  lastName?:  string;
  billingCycle?: 'monthly' | 'yearly';
  planName?: string;
}): PayhereCheckoutData {
  const { userId, planId, orderId, amount, email, firstName = '', lastName = '' } = params;
  const currency = 'LKR';
  const hash = generateHash(orderId, amount, currency);

  const baseUrl = env.PAYHERE_SANDBOX
    ? 'https://sandbox.payhere.lk/pay/checkout'
    : 'https://www.payhere.lk/pay/checkout';

  return {
    merchant_id:  env.PAYHERE_MERCHANT_ID,
    return_url:   `${env.FRONTEND_URL}/dashboard?payment=success`,
    cancel_url:   `${env.FRONTEND_URL}/pricing?payment=cancelled`,
    notify_url:   `${process.env.PAYMENT_SERVICE_PUBLIC_URL ?? 'http://localhost:3014'}/v1/payment/webhook/payhere`,
    order_id:     orderId,
    items:        `DocCraft ${params.planName || 'pro'} Subscription`,
    currency,
    amount,
    first_name:   firstName,
    last_name:    lastName,
    email,
    phone:        '',
    address:      '',
    city:         '',
    country:      'Sri Lanka',
    hash,
    recurrence:   params.billingCycle === 'yearly' ? '1 Year' : '1 Month',
    duration:     'Forever',
    custom_1:     userId,
    custom_2:     planId,
  };
}

export const PAYHERE_CHECKOUT_URL = env.PAYHERE_SANDBOX
  ? 'https://sandbox.payhere.lk/pay/checkout'
  : 'https://www.payhere.lk/pay/checkout';

// ─── Webhook (IPN) event mapping ──────────────────────────────────────────────

/**
 * PayHere IPN payload — a flat form-POST (no typed event name like Paddle).
 * status_code carries the outcome; custom_1/custom_2 carry userId/planId.
 */
export interface PayhereWebhookPayload {
  merchant_id:      string;
  order_id:         string;
  payment_id?:      string;
  payhere_amount:   string;
  payhere_currency: string;
  status_code:      string;
  md5sig:           string;
  custom_1?:        string;   // userId
  custom_2?:        string;   // planId
  subscription_id?: string;
  method?:          string;
}

/**
 * processPayhereWebhook — normalises a verified PayHere IPN into DocCraft
 * actions based on status_code. Idempotent: the composite
 * `payhere:<order_id>:<status_code>` key is recorded so replays are skipped.
 *
 *    2 SUCCESS      → activate subscription, welcome email
 *    0 PENDING      → no action
 *   -1 CANCELLED    → downgrade to free, cancellation email
 *   -2 FAILED       → mark past_due, failed-payment email
 *   -3 CHARGEBACKED → mark past_due, failed-payment email
 */
export async function processPayhereWebhook(payload: PayhereWebhookPayload): Promise<void> {
  const {
    order_id, status_code,
    subscription_id, payhere_amount, payhere_currency,
  } = payload;

  if(process.env.PAYHERE_APP_ID && process.env.PAYHERE_APP_SECRET) {
    await (await import('./payhere-reconciliation.service.js')).reconcilePayhereOrder(order_id);
    return;
  }
  // payment_id, subscription_id and message_type are outside md5sig. Changing
  // those fields must never manufacture another payment or extend access.
  // Installments require Retrieval API reconciliation before automatic renewal.
  const eventId = `payhere:${order_id}:${status_code}`;

  if (await isAlreadyProcessed(eventId)) {
    console.log(`[payment/payhere] Skipping duplicate event: ${eventId}`);
    return;
  }

  const intent = await prisma.checkoutIntent.findUnique({ where: { orderId: order_id } });
  if (!intent) throw new Error('No server-owned checkout record; reconcile this legacy payment manually');
  if (!/^\d+(?:\.\d{1,2})?$/.test(payhere_amount) || Math.round(Number(payhere_amount) * 100) !== intent.amountMinor || payhere_currency !== intent.currency) {
    throw new Error('Payment amount or currency does not match checkout');
  }
  const { userId, planId } = intent;
  if (status_code === '2' && (await isAlreadyProcessed(`payhere:${order_id}:-1`) || await isAlreadyProcessed(`payhere:${order_id}:-3`))) return;

  const statusCode = parseInt(status_code, 10) as PayhereStatus;
  console.log(`[payment/payhere] Processing order ${order_id}, status ${statusCode}`);

  switch (statusCode) {
    // ─── SUCCESS: subscription activated ────────────────────────────────────
    case PAYHERE_STATUS.SUCCESS: {
      if (!planId) break;
      const plan = await prisma.plan.findUnique({ where: { id: planId } });
      if (!plan) break;

      // A retry after a partial cross-service failure keeps the same period.
      const now = intent.createdAt || new Date();
      const periodEnd = new Date(now);
      if (intent.billingCycle === 'yearly') periodEnd.setFullYear(periodEnd.getFullYear() + 1);
      else periodEnd.setMonth(periodEnd.getMonth() + 1);

      const current=await prisma.subscription.findUnique({where:{userId}});
      const priorIntent=current?.payhereOrderId?await prisma.checkoutIntent.findUnique({where:{orderId:current.payhereOrderId}}):null;
      if(current && (current.currentPeriodStart>intent.createdAt || priorIntent && priorIntent.createdAt>intent.createdAt))break;
      await activateProSubscription({
        userId,
        planId:                plan.id,
        planName:              plan.name,
        gateway:               'payhere',
        payhereOrderId:        order_id,
        periodStart:           now,
        periodEnd,
        billingAmountMinor: intent.amountMinor,
        billingCurrency: intent.currency,
        billingCycle: intent.billingCycle as 'monthly' | 'yearly',
      });

      const sub = await prisma.subscription.findUnique({ where: { userId } });
      if (sub) {
        await upsertInvoice({
          userId, subscriptionId: sub.id, gatewayInvoiceId: 'payhere:' + order_id,
          gateway: 'payhere', amount: parseFloat(payhere_amount),
          currency: payhere_currency, status: 'paid', paidAt: now,
        });
      }

      await trackProductEvent(userId, 'subscription_activated', { gateway: 'payhere', plan: plan.name, billing_cycle: intent.billingCycle });

      await queueNotification(userId, 'welcome');
      break;
    }

    // ─── FAILED / CHARGEBACKED ──────────────────────────────────────────────
    case PAYHERE_STATUS.FAILED:
    case PAYHERE_STATUS.CHARGEBACKED: {
      const current=await prisma.subscription.findUnique({where:{userId}});
      if(!current || current.gateway!=='payhere' || current.payhereOrderId!==order_id)break;
      if(statusCode===PAYHERE_STATUS.FAILED && await isAlreadyProcessed(`payhere:${order_id}:2`))break;
      await prisma.subscription.updateMany({
        where: { userId },
        data:  { status: 'past_due', updatedAt: new Date() },
      });

      const sub = await prisma.subscription.findFirst({ where: { userId } });
      if (sub) {
        await upsertInvoice({
          userId, subscriptionId: sub.id, gatewayInvoiceId: 'payhere:' + order_id,
          gateway: 'payhere', amount: parseFloat(payhere_amount),
          currency: payhere_currency, status: 'failed',
        });
      }

      // The admin-configurable automation engine owns this notification (see
      // rule_payment_failed_alert) — Paddle/PayHere stay authoritative for the
      // payment event itself, but its downstream reaction is Admin-managed.
      await emitAutomationEvent('payment.failed', { user_id: userId, gateway: 'payhere', order_id });
      await trackProductEvent(userId, 'payment_failed', { gateway: 'payhere' });
      break;
    }

    // ─── CANCELLED ──────────────────────────────────────────────────────────
    case PAYHERE_STATUS.CANCELLED: {
      const current = await prisma.subscription.findUnique({where:{userId}});
      if (!current || current.gateway !== 'payhere' || current.payhereOrderId !== order_id) break;
      // Quota reset stays a direct call — account-state correctness can't
      // depend on the automation engine/Redis being healthy. The cancellation
      // email is the admin-configurable side effect (rule_subscription_cancelled).
      await downgradeToFree(userId);
      await emitAutomationEvent('subscription.cancelled', { user_id: userId, gateway: 'payhere', order_id });
      await trackProductEvent(userId, 'subscription_cancelled', { gateway: 'payhere' });
      break;
    }

    // ─── PENDING: no action ─────────────────────────────────────────────────
    case PAYHERE_STATUS.PENDING:
    default:
      console.log(`[payment/payhere] No action for status: ${statusCode}`);
  }

  await markProcessed(eventId, 'payhere', `status:${statusCode}`);
}
